package com.chunkworks.heft.mixin.client;

import com.chunkworks.heft.client.HeftClient;
import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import com.llamalad7.mixinextras.injector.wrapoperation.WrapOperation;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.renderer.entity.ItemRenderer;
import net.minecraft.client.resources.model.BakedModel;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;

/**
 * A GUI slot shows the item as the pack draws it (D-0010). The slot picks its lighting from the model it looked up
 * (a flat item lit flat, a block lit as a block) before drawing, so the flat model is handed back at the look-up,
 * not only where it is drawn: a plant Heft draws crossed, lit as a block, would otherwise show its flat sprite dark.
 */
@Mixin(GuiGraphics.class)
public abstract class GuiGraphicsMixin {
    @WrapOperation(method = "renderItem(Lnet/minecraft/world/entity/LivingEntity;Lnet/minecraft/world/level/Level;Lnet/minecraft/world/item/ItemStack;IIII)V",
            at = @At(value = "INVOKE", target = "Lnet/minecraft/client/renderer/entity/ItemRenderer;getModel(Lnet/minecraft/world/item/ItemStack;Lnet/minecraft/world/level/Level;Lnet/minecraft/world/entity/LivingEntity;I)Lnet/minecraft/client/resources/model/BakedModel;"))
    private BakedModel heft$flatInSlots(ItemRenderer renderer, ItemStack stack, Level level, LivingEntity entity, int seed, Operation<BakedModel> original) {
        return HeftClient.flat(original.call(renderer, stack, level, entity, seed));
    }
}
